# TODO: Desenvolva o algoritmo abaixo:
codigo = int(input("codigo: "))
quantidade = int(input("quantidade: "))
precos = {
    1: 4.00,
    2: 4.50,
    3: 5.00,
    4: 2.00,
    5: 1.50
}
total = precos.get(codigo, 0) * quantidade
print(f"Total a pagar: R$ {total:.2f}")